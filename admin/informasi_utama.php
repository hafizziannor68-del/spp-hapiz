<h1>MAU NYERAH...</h1>
<hr>

<p>
    Kadang rasanya pengen berhenti. Lelah sama semuanya.
</p>

<p>
    Rasanya dunia terlalu berat, masalah datang satu per satu, dan senyum yang dipasang setiap hari mulai terasa palsu.
    Ada saat di mana hati cuma ingin menyerah dan menghilang dari semua rasa capek ini.
</p>

<p>
    Tapi setiap kali pikiran itu datang, yang pertama terlintas justru wajah orang tua.
    Semua perjuangan mereka, semua pengorbanan yang mereka lakukan, dan harapan yang mereka titipkan.
</p>

<p>
    <b>Aku nggak mau mereka menangis karena kehilangan seseorang yang selama ini mereka perjuangkan.</b>
    Mungkin aku lelah, mungkin aku ingin berhenti, tapi aku juga tahu mereka akan jauh lebih hancur kalau aku benar-benar menyerah.
</p>

<p>
    Jadi untuk hari ini... aku memilih bertahan.
    Bukan karena semuanya sudah baik-baik saja, tapi karena masih ada orang yang sangat menyayangiku dan ingin melihatku tetap ada.
</p>

<p>
    Semoga suatu saat nanti, semua rasa lelah ini berubah menjadi cerita bahwa aku berhasil melewatinya.
</p>
